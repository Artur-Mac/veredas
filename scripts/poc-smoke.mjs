import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright';

const base = process.env.POC_URL || 'http://localhost:8087';
await mkdir('out/poc', { recursive: true });
const browser = await chromium.launch({ headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, permissions: ['clipboard-read', 'clipboard-write'] });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  await page.goto(`${base}/`);
  await page.getByRole('button', { name: 'Abrir minhas análises', exact: true }).waitFor();
  await page.getByRole('textbox', { name: 'Colar link', exact: true }).fill('https://example.com/imovel-boa-viagem');
  assert.equal(new URL(page.url()).pathname, '/');
  await page.getByRole('button', { name: 'Continuar', exact: true }).click();
  await page.getByRole('textbox', { name: 'Nome do imóvel *', exact: true }).waitFor();
  assert.equal(new URL(page.url()).pathname, '/analise');
  await page.getByRole('button', { name: 'Salvar análise', exact: true }).click();
  await page.getByText('Dê um nome para encontrar este imóvel depois.').waitFor();
  await page.getByRole('textbox', { name: 'Nome do imóvel *', exact: true }).fill('Apartamento Aurora');
  await page.getByRole('textbox', { name: 'Bairro ou região', exact: true }).fill('Recife');
  await page.getByRole('textbox', { name: 'Aluguel / mês', exact: true }).fill('2.500');
  await page.getByRole('textbox', { name: 'Condomínio / mês', exact: true }).fill('500');
  await page.getByRole('textbox', { name: 'IPTU / ano', exact: true }).fill('1200');
  await page.getByRole('textbox', { name: 'Área / m²', exact: true }).fill('60');
  await page.getByRole('checkbox', { name: 'Ouvir o ruído com janelas abertas e fechadas.' }).click();
  await page.getByRole('textbox', { name: 'Anotações da visita', exact: true }).fill('Conferir janela da sala às 15h.');
  await page.getByRole('button', { name: 'Salvar análise', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Análise salva neste aparelho.' }).waitFor();
  await page.getByRole('button', { name: 'Copiar perguntas para o corretor' }).click();
  const clipboard = await page.evaluate(() => navigator.clipboard.readText());
  assert(clipboard.includes('Apartamento Aurora'));
  assert(!clipboard.includes('Ouvir o ruído'));
  await page.getByRole('button', { name: 'Ver minhas análises' }).click();
  await page.reload();
  await page.getByRole('button', { name: 'Abrir análise de Apartamento Aurora' }).click();
  assert.equal(await page.getByRole('textbox', { name: 'Aluguel / mês', exact: true }).inputValue(), '2.500');
  assert.equal(await page.getByRole('textbox', { name: 'Anotações da visita', exact: true }).inputValue(), 'Conferir janela da sala às 15h.');
  assert.equal(await page.getByRole('checkbox', { name: 'Ouvir o ruído com janelas abertas e fechadas.' }).isChecked(), true);
  await page.getByRole('textbox', { name: 'Aluguel / mês', exact: true }).fill('2.700');
  await page.getByRole('button', { name: 'Salvar análise', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Análise salva neste aparelho.' }).waitFor();
  await page.setViewportSize({ width: 375, height: 812 });
  await page.getByRole('textbox', { name: 'Nome do imóvel *', exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'out/poc/mobile-editor.png' });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.getByRole('button', { name: 'Ver minhas análises' }).click();
  await page.getByRole('button', { name: 'Adicionar imóvel' }).click();
  await page.getByRole('textbox', { name: 'Nome do imóvel *', exact: true }).fill('Apartamento Jardim');
  await page.getByRole('textbox', { name: 'Aluguel / mês', exact: true }).fill('3.000');
  await page.getByRole('button', { name: 'Salvar análise', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Análise salva neste aparelho.' }).waitFor();
  await page.getByRole('button', { name: 'Ver minhas análises' }).click();
  await page.getByRole('checkbox', { name: 'Comparar Apartamento Aurora' }).click();
  await page.getByRole('checkbox', { name: 'Comparar Apartamento Jardim' }).click();
  await page.getByRole('heading', { name: 'Lado a lado.', exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'out/poc/mobile-comparacao.png' });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('heading', { name: 'Cada imóvel, uma possibilidade.', exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'out/poc/desktop-caderno.png' });
  await page.emulateMedia({ colorScheme: 'dark', reducedMotion: 'reduce' });
  await page.screenshot({ path: 'out/poc/desktop-escuro.png' });
  await page.getByRole('button', { name: 'Abrir análise de Apartamento Jardim' }).click();
  await page.getByRole('button', { name: 'Excluir análise', exact: true }).click();
  await page.getByRole('button', { name: 'Confirmar exclusão desta análise' }).click();
  await page.getByRole('button', { name: 'Adicionar imóvel' }).waitFor();
  await page.reload();
  await page.getByRole('button', { name: 'Adicionar imóvel' }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Abrir análise de Apartamento Jardim' }).count(), 0);
  assert.equal(await page.getByRole('button', { name: 'Abrir análise de Apartamento Aurora' }).count(), 1);
  assert.deepEqual(errors, []);
  console.log('POC: entrada, validação, cálculos, gravação, recarga, edição, checklist, cópia, comparação, exclusão e responsividade passaram.');
} finally { await browser.close(); }
